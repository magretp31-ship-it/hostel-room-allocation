DROP VIEW IF EXISTS v_room_occupancy CASCADE;
DROP TABLE IF EXISTS occupancy_snapshot, allocations, rooms, students CASCADE;

CREATE TABLE students (
    student_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_number VARCHAR(30) NOT NULL UNIQUE,
    full_name VARCHAR(120) NOT NULL
);

CREATE TABLE rooms (
    room_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_number VARCHAR(20) NOT NULL UNIQUE,
    capacity INTEGER NOT NULL CHECK (capacity > 0)
);

CREATE TABLE allocations (
    allocation_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id INTEGER NOT NULL REFERENCES students(student_id),
    room_id INTEGER NOT NULL REFERENCES rooms(room_id),
    allocated_on DATE NOT NULL,
    released_on DATE,
    status VARCHAR(10) NOT NULL CHECK (status IN ('ACTIVE', 'ENDED')),
    CHECK (
        (status = 'ACTIVE' AND released_on IS NULL) OR
        (status = 'ENDED' AND released_on IS NOT NULL)
    )
);

CREATE TABLE occupancy_snapshot (
    snapshot_date DATE NOT NULL,
    room_id INTEGER NOT NULL REFERENCES rooms(room_id),
    occupied_beds INTEGER NOT NULL CHECK (occupied_beds >= 0),
    free_beds INTEGER NOT NULL CHECK (free_beds >= 0),
    PRIMARY KEY(snapshot_date, room_id)
);

-- Partial unique index ensures one ACTIVE allocation per student, including direct SQL.
CREATE UNIQUE INDEX uq_one_active_allocation_per_student
ON allocations(student_id) WHERE status = 'ACTIVE';

-- (d) Trigger enforces capacity for inserts/updates.
CREATE OR REPLACE FUNCTION fn_check_allocation_rules()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
    v_capacity INTEGER;
    v_occupied BIGINT;
BEGIN
    IF NEW.status = 'ACTIVE' THEN
        SELECT capacity INTO v_capacity FROM rooms WHERE room_id = NEW.room_id;
        IF NOT FOUND THEN RAISE EXCEPTION 'Unknown room ID: %', NEW.room_id; END IF;

        SELECT COUNT(*) INTO v_occupied
        FROM allocations a
        WHERE a.room_id = NEW.room_id
          AND a.status = 'ACTIVE'
          AND a.allocation_id <> COALESCE(NEW.allocation_id, -1);

        IF v_occupied >= v_capacity THEN
            RAISE EXCEPTION 'Room % is full', NEW.room_id;
        END IF;

        IF EXISTS (
            SELECT 1 FROM allocations a
            WHERE a.student_id = NEW.student_id
              AND a.status = 'ACTIVE'
              AND a.allocation_id <> COALESCE(NEW.allocation_id, -1)
        ) THEN
            RAISE EXCEPTION 'Student already has an ACTIVE allocation';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_allocation_rules
BEFORE INSERT OR UPDATE ON allocations
FOR EACH ROW EXECUTE FUNCTION fn_check_allocation_rules();

-- (b) Free beds excludes ENDED allocations.
CREATE OR REPLACE FUNCTION fn_free_beds(p_room_id INTEGER)
RETURNS INTEGER LANGUAGE plpgsql AS $$
DECLARE v_capacity INTEGER; v_occupied INTEGER;
BEGIN
    SELECT capacity INTO v_capacity FROM rooms WHERE room_id = p_room_id;
    IF NOT FOUND THEN RAISE EXCEPTION 'Unknown room ID: %', p_room_id; END IF;

    SELECT COUNT(*) INTO v_occupied FROM allocations
    WHERE room_id = p_room_id AND status = 'ACTIVE';
    RETURN v_capacity - v_occupied;
END;
$$;

-- (c) Allocation procedure validates IDs, uniqueness and capacity.
CREATE OR REPLACE PROCEDURE pr_allocate_room(
    p_student_id INTEGER, p_room_id INTEGER, p_allocated_on DATE
)
LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM students WHERE student_id = p_student_id) THEN
        RAISE EXCEPTION 'Unknown student ID: %', p_student_id;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM rooms WHERE room_id = p_room_id) THEN
        RAISE EXCEPTION 'Unknown room ID: %', p_room_id;
    END IF;
    IF p_allocated_on IS NULL THEN RAISE EXCEPTION 'Allocation date is required'; END IF;
    IF EXISTS (SELECT 1 FROM allocations WHERE student_id = p_student_id AND status = 'ACTIVE') THEN
        RAISE EXCEPTION 'Student already has an ACTIVE allocation';
    END IF;
    IF fn_free_beds(p_room_id) <= 0 THEN
        RAISE EXCEPTION 'Room is full';
    END IF;

    INSERT INTO allocations(student_id, room_id, allocated_on, released_on, status)
    VALUES (p_student_id, p_room_id, p_allocated_on, NULL, 'ACTIVE');
END;
$$;

